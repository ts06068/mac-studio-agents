#!/bin/bash
# Download beside your own llm.env, then run: bash curl-llm.sh "Your question"
set -euo pipefail

usage() {
    cat <<'EOF'
Usage:
  bash curl-llm.sh --models
  bash curl-llm.sh [--stream|--no-stream] "Your question"

Default: streaming, up to 512 output tokens.
Overrides: MAX_TOKENS=2048 LLM_TIMEOUT=3600 bash curl-llm.sh "Your question"
Requires curl and jq. Loads llm.env next to this script if present, or uses
OPENAI_BASE_URL, OPENAI_API_KEY, and LLM_MODEL from the current environment.
Set LLM_ENV_FILE to load a different environment file.
EOF
}

mode=stream
case "${1:-}" in
    --help|-h) usage; exit 0 ;;
    --models) mode=models; shift ;;
    --stream) shift ;;
    --no-stream) mode=plain; shift ;;
    --*) usage >&2; exit 2 ;;
esac
if [[ "$mode" == models ]]; then
    [[ "$#" -eq 0 ]] || { usage >&2; exit 2; }
else
    [[ "$#" -eq 1 ]] || { usage >&2; exit 2; }
fi
for tool in curl jq; do
    command -v "$tool" >/dev/null || { echo "Install $tool first." >&2; exit 1; }
done
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
env_file="${LLM_ENV_FILE:-$script_dir/llm.env}"
if [[ -f "$env_file" ]]; then
    # This is your own credential file, generated by scripts/msa bundle.
    source "$env_file"
elif [[ -n "${LLM_ENV_FILE:-}" ]]; then
    echo "Environment file does not exist: $env_file" >&2
    exit 1
fi
: "${OPENAI_BASE_URL:?Download your llm.env beside this script or set OPENAI_BASE_URL}"
: "${OPENAI_API_KEY:?Download your llm.env beside this script or set OPENAI_API_KEY}"
base_url="${OPENAI_BASE_URL%/}"
model="${LLM_MODEL:-gemma-4-31b}"
timeout="${LLM_TIMEOUT:-3600}"
if [[ "$mode" == models ]]; then
    curl --fail-with-body --silent --show-error --connect-timeout 15 --max-time 30 \
        -H "Authorization: Bearer $OPENAI_API_KEY" "$base_url/models" | jq .
    exit 0
fi
max_tokens="${MAX_TOKENS:-512}"
[[ "$max_tokens" =~ ^[1-9][0-9]*$ ]] || { echo 'MAX_TOKENS must be a positive integer.' >&2; exit 2; }
stream=false
[[ "$mode" != stream ]] || stream=true
payload="$(jq -cn --arg model "$model" --arg prompt "$1" \
    --argjson max_tokens "$max_tokens" --argjson stream "$stream" \
    '{model:$model,messages:[{role:"user",content:$prompt}],max_tokens:$max_tokens,stream:$stream}')"
request() {
    curl --no-buffer --fail-with-body --silent --show-error \
        --connect-timeout 15 --max-time "$timeout" \
        "$base_url/chat/completions" \
        -H "Authorization: Bearer $OPENAI_API_KEY" \
        -H 'Content-Type: application/json' --data-binary "$payload"
}
if [[ "$mode" == stream ]]; then
    request | jq -jR --unbuffered '
        select(startswith("data: ")) | ltrimstr("data: ")
        | select(. != "[DONE]") | fromjson
        | if .error then error(.error.message // "API error")
          else .choices[0].delta.content // empty end'
    printf '\n'
else
    request | jq -r '
        if .error then error(.error.message // "API error")
        else .choices[0].message.content // "" end'
fi
